let lang = 'ar';
export function initAdminLanguage() {
  try {
    lang = localStorage.getItem('ahc-admin-lang') === 'en' ? 'en' : 'ar';
  } catch {
    lang = 'ar';
  }
  applyAdminLanguage();
  return lang;
}
export function toggleAdminLanguage() {
  lang = lang === 'ar' ? 'en' : 'ar';
  try {
    localStorage.setItem('ahc-admin-lang', lang);
  } catch {
    /* not remembered */
  }
  applyAdminLanguage();
  return lang;
}
export function adminLang() {
  return lang;
}
export function applyAdminLanguage() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-t]').forEach((el) => {
    el.textContent = at(el.dataset.t);
  });
  document.querySelectorAll('[data-t-attr]').forEach((el) => {
    for (const pair of el.dataset.tAttr.split(';')) {
      const [attr, key] = pair.split(':');
      el.setAttribute(attr.trim(), at(key.trim()));
    }
  });
}
